#!/usr/bin/env bash

# Stop the script if a command fails
set -e

# Store tool information
TOOL_NAME="FungiFunk_summary"
VERSION="0.1.9"

# Get the directory where this wrapper script is located
script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"

# Define the Python script path relative to this wrapper
summary_script="${script_dir}/FungiFunk_summary.py"

# Use the current Python by default, but allow users to override it with PYTHON=/path/to/python
python_cmd="${PYTHON:-python}"

# Preserve the original command-line arguments exactly as supplied
ORIGINAL_ARGS=("$@")

# Save a shell-escaped representation of the command for logging
COMMAND_RUN="$(printf '%q ' "$0" "${ORIGINAL_ARGS[@]}")"
COMMAND_RUN="${COMMAND_RUN% }"


########################################################################################################
# Help
########################################################################################################

Help() {
    echo "   _____                  _ _____            _                                                            "
    echo "  |  ___|   _ _ __   __ _(_)  ___|   _ _ __ | | __     ___ _   _ _ __ ___  _ __ ___   __ _ _ __ _   _     "
    echo "  | |_ | | | |  _ \ / _  | | |_ | | | |  _ \| |/ /    / __| | | |  _   _ \|  _   _ \ / _  |  __| | | |    "
    echo "  |  _|| |_| | | | | (_| | |  _|| |_| | | | |   <     \__ \ |_| | | | | | | | | | | | (_| | |  | |_| |    "
    echo "  |_|   \__,_|_| |_|\__, |_|_|   \__,_|_| |_|_|\_\____|___/\__,_|_| |_| |_|_| |_| |_|\__,_|_|   \__, |    "
    echo "                    |___/                                                                       |___/     "
    echo "                                                                                                          "
    echo "${TOOL_NAME} v${VERSION}: summary module for FungiFunk"
    echo ""
    echo "Summarises and compares outputs from multiple FungiFunk runs."
    echo "Accepts results generated by FungiFunk_batch or by independent FungiFunk runs."
    echo "Generates count matrices, summary tables and an interactive HTML report."
    echo ""
    echo "##########################"
    echo "         USAGE            "
    echo "##########################"
    echo "  FungiFunk_summary.sh --input_dir <dir> --outdir <dir> [optional arguments]"
    echo ""
    echo "##########################"
    echo "         ARGUMENTS        "
    echo "##########################"
    echo "Required:"
    echo "  --input_dir <dir>                   Directory containing FungiFunk outputs. The directory is searched recursively"
    echo "  --outdir <dir>                      Output directory for FungiFunk summary results"
    echo ""
    echo "Optional:"
    echo "  -t, --threads <int>                 Number of threads [default = 1]"
    echo "  --normalise_cpm                     Write additional CPM-normalised matrices"
    echo "                                       CPM is calculated separately for each count table using"
    echo "                                       the total count sum of each sample in that table"
    echo "                                       This does not use the original FASTQ read counts"
    echo "                                       For multi-value annotation fields, CPM represents counts per"
    echo "                                       million annotation assignments"
    echo "  --strict                            Stop with an error if expected files are missing or inconsistent"
    echo "                                       By default, FungiFunk_summary warns and continues with available files"
    echo "  --skip_html_report                  Do not generate the HTML report. By default, the HTML report is generated"
    echo "  --html_top_n <int>                  Number of top functional features to display in the HTML report"
    echo "                                       Features are ranked by total count across samples. [Default = 50]"
    echo "  --html_no_top                       Do not limit the number of functional features shown in the HTML report"
    echo "                                       Warning: this may create a very large and slow HTML file 
                                                          and make the run much more RAM-intensive."
    echo "  --calculate_pfam_eggnog_context     Calculate dataset-derived context for PFAM and eggNOG OG features."
    echo "                                       This adds top-associated protein name and description columns"
    echo "                                       to PFAM and eggNOG OG feature metadata and HTML tables."
    echo "                                       This step scans annotation tables and may increase runtime."
    echo "  --timestamps                        Add timestamps to FungiFunk_summary progress messages"
    echo "  --version                           Show version information and exit"
    echo "  -h, --help                          Show this help message and exit"
    echo ""
    echo "##########################"
    echo "         OUTPUTS"
    echo "##########################"
    echo "Default:"
    echo "  FungiFunk_summary_report.html               Interactive HTML report, unless --skip_html_report is used"
    echo ""
    echo "  matrices/"
    echo "     protein_read_count_matrix.tsv            Raw protein read count matrix"
    echo "     ko_read_count_matrix.tsv                 Raw KEGG ortholog count matrix"
    echo "     eggnog_ogs_read_count_matrix.tsv         Raw eggNOG OG count matrix"
    echo "     cazy_read_count_matrix.tsv               Raw CAZy count matrix"
    echo "     pfam_read_count_matrix.tsv               Raw PFAM count matrix"
    echo ""
    echo "  summaries/"
    echo "    detected_output_files.tsv                 Inventory of detected FungiFunk output files"
    echo "    sample_summary.tsv                        Per-sample overview of available output tables"
    echo "    annotation_summary.tsv                    Summary statistics from annotation tables"
    echo "    detected_features_summary.tsv             Number of detected features per sample"
    echo "    protein_metadata.tsv                      Non-redundant protein annotation metadata"
    echo ""
    echo "    summaries/feature_metadata/"
    echo "      protein_feature_metadata.tsv            Metadata for selected protein features"
    echo "      ko_metadata.tsv                         Context metadata for selected KEGG KO features"
    echo "      cazy_metadata.tsv                       CAZy class metadata for selected CAZy features"
    echo "      pfam_metadata.tsv                       Derived context for selected PFAM features"
    echo "      eggnog_ogs_metadata.tsv                 Derived context for selected eggNOG OG features"
    echo ""
    echo "Optional:"
    echo "    matrices/                                 Only written when --normalise_cpm is used"
    echo "      protein_read_count_cpm_matrix.tsv       CPM-normalised protein read count matrix"
    echo "      ko_read_count_cpm_matrix.tsv            CPM-normalised KEGG ortholog count matrix"
    echo "      eggnog_ogs_read_count_cpm_matrix.tsv    CPM-normalised eggNOG OG count matrix"
    echo "      cazy_read_count_cpm_matrix.tsv          CPM-normalised CAZy count matrix"
    echo "      pfam_read_count_cpm_matrix.tsv          CPM-normalised PFAM count matrix"
    echo ""
    echo "  Notes:"
    echo "    Feature metadata tables are used to make the HTML functional feature tables easier to interpret."
    echo "    PFAM and eggNOG OG context is derived from associated protein annotations in the FungiFunk outputs."
    echo "    It should not be interpreted as official PFAM or eggNOG database metadata."
    echo "    The HTML report is generated by default. Use --skip_html_report to disable it."
    echo ""
}

# Show help if no arguments are provided
if [[ $# -eq 0 ]]; then
    Help
    exit 0
fi

########################################################################################################
# Define default values for arguments
########################################################################################################

input_dir=""
outdir=""
normalise_cpm="false"
strict="false"
skip_html_report="false"
timestamps="false"
threads="1"
html_top_n="50"
html_no_top="false"
calculate_pfam_eggnog_context="false"


########################################################################################################
# Parse arguments
########################################################################################################
while [[ "$#" -gt 0 ]]; do
    case "$1" in
        --input_dir)
            input_dir="$2"
            shift 2
            ;;
        --outdir)
            outdir="$2"
            shift 2
            ;;
        -t|--threads)
            threads="$2"
            shift 2
            ;;
        --normalise_cpm)
            normalise_cpm="true"
            shift
            ;;
        --strict)
            strict="true"
            shift
            ;;
        --skip_html_report)
            skip_html_report="true"
            shift
            ;;
        --html_top_n)
            html_top_n="$2"
            shift 2
            ;;
        --html_no_top)
            html_no_top="true"
            shift
            ;;
        --calculate_pfam_eggnog_context)
            calculate_pfam_eggnog_context="true"
            shift
            ;;
        --timestamps)
            timestamps="true"
            shift
            ;;
        --version)
            echo "${TOOL_NAME} v${VERSION}"
            exit 0
            ;;
        -h|--help)
            Help
            exit 0
            ;;
        *)
            echo "ERROR: Unknown argument: $1" >&2
            exit 1
            ;;
    esac
done


########################################################################################################
# Validate arguments
########################################################################################################

# Check that the Python script exists
if [[ ! -f "$summary_script" ]]; then
    echo "ERROR: Could not find ${summary_script}" >&2
    exit 1
fi

# Check that threads is a positive integer
if ! [[ "$threads" =~ ^[0-9]+$ ]] || [[ "$threads" -lt 1 ]]; then
    echo "ERROR: --threads must be a positive integer" >&2
    exit 1
fi

if [[ "$threads" -lt 1 ]]; then
    echo "ERROR: --threads must be at least 1" >&2
    exit 1
fi

# Check that html_top_n is a positive integer
if ! [[ "$html_top_n" =~ ^[0-9]+$ ]] || [[ "$html_top_n" -lt 1 ]]; then
    echo "ERROR: --html_top_n must be a positive integer"
    exit 1
fi


########################################################################################################
# Prepare output directories and log file
########################################################################################################

# Create the output directory before writing the run metadata log
mkdir -p "$outdir"

# Define run metadata log file
run_info_log="${outdir}/FungiFunk_summary_run_info.log"

# Write run metadata to log file
cat > "$run_info_log" <<EOF
Tool: ${TOOL_NAME}
Version: ${VERSION}
Run date: $(date '+%Y-%m-%d %H:%M:%S')
Working directory: $(pwd)
Command: ${COMMAND_RUN}

Input:
  input_dir: ${input_dir}
  outdir: ${outdir}

Run options:
  threads: ${threads}
  normalise_cpm: ${normalise_cpm}
  strict: ${strict}
  timestamps: ${timestamps}

HTML report options:
  skip_html_report: ${skip_html_report}
  html_top_n: ${html_top_n}
  html_no_top: ${html_no_top}
  calculate_pfam_eggnog_context: ${calculate_pfam_eggnog_context}

EOF


########################################################################################################
# Print run start messages
########################################################################################################

echo "###################################################################################################"
echo "   _____                  _ _____            _                                                            "
echo "  |  ___|   _ _ __   __ _(_)  ___|   _ _ __ | | __     ___ _   _ _ __ ___  _ __ ___   __ _ _ __ _   _     "
echo "  | |_ | | | |  _ \ / _  | | |_ | | | |  _ \| |/ /    / __| | | |  _   _ \|  _   _ \ / _  |  __| | | |    "
echo "  |  _|| |_| | | | | (_| | |  _|| |_| | | | |   <     \__ \ |_| | | | | | | | | | | | (_| | |  | |_| |    "
echo "  |_|   \__,_|_| |_|\__, |_|_|   \__,_|_| |_|_|\_\____|___/\__,_|_| |_| |_|_| |_| |_|\__,_|_|   \__, |    "
echo "                    |___/                                                                       |___/     "
echo "                                                                                                          "
echo "Running ${TOOL_NAME} v${VERSION}"
echo "Input directory: ${input_dir}"
echo "Output directory: ${outdir}"
echo "Run information log: ${run_info_log}"
echo ""


########################################################################################################
# Create flags and additional functions
########################################################################################################

threads_flag=""
if [[ -n "$threads" ]]; then
    threads_flag="--threads $threads"
fi

normalise_cpm_flag=""
if [[ "$normalise_cpm" == "true" ]]; then
    normalise_cpm_flag="--normalise_cpm"
fi

strict_flag=""
if [[ "$strict" == "true" ]]; then
    strict_flag="--strict"
fi

skip_html_report_flag=""
if [[ "$skip_html_report" == "true" ]]; then
    skip_html_report_flag="--skip_html_report"
fi

html_no_top_flag=""
if [[ "$html_no_top" == "true" ]]; then
    html_no_top_flag="--html_no_top"
fi

calculate_pfam_eggnog_context_flag=""
if [[ "$calculate_pfam_eggnog_context" == "true" ]]; then
    calculate_pfam_eggnog_context_flag="--calculate_pfam_eggnog_context"
fi

timestamps_flag=""
if [[ "$timestamps" == "true" ]]; then
    timestamps_flag="--timestamps"
fi


########################################################################################################
# Run summary script
########################################################################################################

# Run the Python summary script and pass all user arguments to it
python "$summary_script" \
    --input_dir "$input_dir" \
    --outdir "$outdir" \
    $threads_flag \
    $normalise_cpm_flag \
    $strict_flag \
    $skip_html_report_flag \
    --html_top_n "$html_top_n" \
    $html_no_top_flag \
    $calculate_pfam_eggnog_context_flag \
    $timestamps_flag \
    --run_info_log "$run_info_log"